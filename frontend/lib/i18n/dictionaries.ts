export type Dictionary = typeof ru;

const dictionaries: Record<Locale, Dictionary> = { ru, kk, en };

export function getDictionary(locale: Locale): Dictionary {
  return dictionaries[locale];
}

// Course.level is always one of the fixed backend strings
// ("beginner"/"intermediate"/"advanced") — never user-facing text on its
// own, so it needs its own small lookup rather than going through
// getDictionary's free-text keys.
export function localizeLevel(level: string, dict: Dictionary): string {
  switch (level) {
    case "beginner":
      return dict.courses.levelBeginner;
    case "intermediate":
      return dict.courses.levelIntermediate;
    case "advanced":
      return dict.courses.levelAdvanced;
    default:
      return level;
  }
}
