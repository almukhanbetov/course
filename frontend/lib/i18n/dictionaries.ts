// Kazakh nouns after a cardinal numeral stay in the singular form
// regardless of count (e.g. "3 курс", never "3 курстар") — unlike Russian's
// three-way plural or English's simple singular/plural.
function kkCount(n: number, word: string): string {
  return `${n} ${word}`;
}

function enCount(n: number, singular: string, plural: string): string {
  return `${n} ${n === 1 ? singular : plural}`;
}

